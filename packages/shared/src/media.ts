import type { AudioFormat, LockReason, Tier } from './tiers.js';

/** Normalised shape emitted by the extraction service, independent of yt-dlp's schema. */
export type MediaKind = 'video' | 'audio' | 'image' | 'live';

export type DeliveryProtocol = 'https' | 'hls' | 'dash' | 'm3u8_native';

export type StreamContainer = 'mp4' | 'webm' | 'mkv' | 'm4a' | 'mp3' | 'ts' | 'unknown';

export interface MediaFormat {
  /** Stable id used when requesting this exact rendition. yt-dlp `format_id`. */
  id: string;
  /** `video+audio` muxed, video-only or audio-only. */
  track: 'muxed' | 'video' | 'audio';
  container: StreamContainer;
  protocol: DeliveryProtocol;
  width: number | null;
  height: number | null;
  fps: number | null;
  /** Human label such as `1080p60` or `Audio 160 kbps`. */
  label: string;
  videoCodec: string | null;
  audioCodec: string | null;
  /** Total bitrate in kbps when known. */
  bitrateKbps: number | null;
  /** Exact size when reported, else yt-dlp's estimate. `null` for live/manifests. */
  sizeBytes: number | null;
  sizeIsEstimate: boolean;
  hasAudio: boolean;
  hasVideo: boolean;
  /** True when the platform only offers this rendition split across two streams. */
  requiresMux: boolean;
}

/** A format decorated with the caller's entitlement. Never sent undecorated. */
export interface GatedMediaFormat extends MediaFormat {
  allowed: boolean;
  lockReason: LockReason | null;
  /** Cheapest tier that unlocks this rendition. */
  requiredTier: Tier;
}

export interface SubtitleTrack {
  lang: string;
  label: string;
  /** `vtt` after normalisation — the worker converts srt/ttml on the fly. */
  ext: 'vtt';
  autoGenerated: boolean;
  /** Proxied URL, never the upstream one. */
  url: string;
}

export interface Thumbnail {
  url: string;
  width: number | null;
  height: number | null;
}

export interface MediaMetadata {
  /** Deterministic id derived from the canonical URL — used for cache keys/routes. */
  id: string;
  sourceUrl: string;
  canonicalUrl: string;
  extractor: string;
  platform: string;
  kind: MediaKind;
  title: string;
  description: string | null;
  durationSeconds: number | null;
  uploader: string | null;
  uploaderUrl: string | null;
  uploadDate: string | null;
  viewCount: number | null;
  likeCount: number | null;
  isLive: boolean;
  ageLimit: number;
  thumbnails: Thumbnail[];
  bestThumbnail: string | null;
  subtitles: SubtitleTrack[];
  chapters: Array<{ title: string; startSeconds: number; endSeconds: number }>;
}

export interface ExtractionResult {
  media: MediaMetadata;
  formats: GatedMediaFormat[];
  /** Rendition the player opens with — the best the caller is entitled to. */
  recommendedFormatId: string | null;
  /** Set when the caller's tier trimmed the list. Drives the upsell banner. */
  lockedFormatCount: number;
  tier: Tier;
  cachedAt: string;
  expiresAt: string;
}

export type JobType = 'download' | 'transcode-audio' | 'mux';

export type JobState =
  | 'queued'
  | 'extracting'
  | 'downloading'
  | 'processing'
  | 'completed'
  | 'failed'
  | 'cancelled';

export interface JobProgress {
  state: JobState;
  /** 0-100. */
  percent: number;
  downloadedBytes: number | null;
  totalBytes: number | null;
  speedBytesPerSecond: number | null;
  etaSeconds: number | null;
  stage: string | null;
}

export interface JobSummary {
  id: string;
  type: JobType;
  state: JobState;
  progress: JobProgress;
  mediaTitle: string;
  formatLabel: string;
  createdAt: string;
  completedAt: string | null;
  error: string | null;
  /** Signed, short-lived artifact URL. Present only in `completed`. */
  downloadUrl: string | null;
  expiresAt: string | null;
}

export interface QuotaSnapshot {
  tier: Tier;
  downloadsUsed: number;
  downloadsLimit: number;
  /** ISO timestamp when the oldest counted download falls out of the window. */
  windowResetsAt: string | null;
  activeJobs: number;
  concurrencyLimit: number;
  maxHeight: number;
  maxFileSizeBytes: number;
}

export interface DownloadRequest {
  url: string;
  formatId: string;
  /** Present for audio-extraction jobs. */
  audioFormat?: AudioFormat;
  /** Burn subtitles / embed as soft track. */
  embedSubtitles?: boolean;
  subtitleLang?: string;
}

export interface AuthUser {
  id: string;
  email: string;
  displayName: string | null;
  tier: Tier;
  emailVerified: boolean;
  subscriptionStatus: string | null;
  subscriptionEndsAt: string | null;
  createdAt: string;
}

export interface ApiError {
  error: {
    code: string;
    message: string;
    /** Present on 403 quota/entitlement failures so the UI can deep-link pricing. */
    requiredTier?: Tier;
    retryAfterSeconds?: number;
    details?: unknown;
  };
}

export type ApiResult<T> = { data: T } | ApiError;
